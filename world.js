const DEFS = {
  village: villageDef,
  mistwood: mistDef,
  salt: saltDef,
  library: libDef,
  dawn: dawnDef
};

export function loadZone(id) {
  const def = DEFS[id] || DEFS.village;
  const tiles = def.tiles;
  const h = tiles.length;
  const w = tiles[0].length;
  const objects = buildObjects(def);
  return {
    id: def.id,
    name: def.name,
    bg: def.bg,
    parallax: def.parallax,
    tiles,
    w, h,
    pixelW: w * TILE,
    pixelH: h * TILE,
    spawn: def.spawn,
    objects,
    puzzle: def.puzzle
  };
}


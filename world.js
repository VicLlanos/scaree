/**
 * EMBER & ECHO — 5 zone definitions (side-scrolling platform layouts)
 * Tile codes: # solid  . air  = one-way  ~ water  F fire
 */
import { TILE } from './physics.js';
import {
  Crate, PressurePlate, Lever, Door, MovingPlatform,
  Rune, Shard, NPC, Portal
} from './entities.js';

export const SOLID_TILES = new Set(['#']);
export function isSolid(t, oneWayCheck) {
  if (t === '#') return true;
  if (t === '=' && oneWayCheck) return true;
  return false;
}
export function isHazard(t) {
  return t === '~' || t === 'F';
}

/** Parse a row-string map into 2D array */
function parse(rows) {
  return rows.map(r => r.split(''));
}

function buildObjects(def) {
  const objs = {
    crates: [], plates: [], levers: [], doors: [],
    platforms: [], runes: [], shards: [], npcs: [], portals: []
  };
  (def.crates || []).forEach((c, i) => objs.crates.push(new Crate('c' + i, c.x, c.y)));
  (def.plates || []).forEach((p, i) => objs.plates.push(new PressurePlate('p' + i, p.x, p.y, p.door)));
  (def.levers || []).forEach((l, i) => objs.levers.push(new Lever('l' + i, l.x, l.y, l.door)));
  (def.doors || []).forEach((d, i) => objs.doors.push(new Door('d' + i, d.x, d.y)));
  (def.platforms || []).forEach((p, i) => objs.platforms.push(new MovingPlatform('m' + i, p.x1, p.y1, p.x2, p.y2, p.period)));
  (def.runes || []).forEach((r, i) => objs.runes.push(new Rune('r' + i, r.x, r.y)));
  (def.shards || []).forEach((s, i) => objs.shards.push(new Shard('s' + i, s.x, s.y, s.index)));
  (def.npcs || []).forEach((n, i) => objs.npcs.push(new NPC('n' + i, n.x, n.y, n.name, n.lines)));
  (def.portals || []).forEach(p => objs.portals.push(new Portal(p.x, p.y, p.to, p.tx, p.ty)));
  return objs;
}

